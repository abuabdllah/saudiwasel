export function getRegionalCity(slug) { return { ...cityData[slug], slug, districts: districtProfiles[slug] }; }
export function getRegionalOperator(slug, operator) {
  const city = getRegionalCity(slug);
  const angle = operatorAngles[operator.slug];
  const intro = [
    `${city.intro[0]} ${angle.intro[0]}`,
    `${city.intro[1]} ${angle.intro[1]}`,
  ];
  const districtLeads = {
    stc: "عند فحص عنوان STC، ",
    salam: "ضمن مراجعة خدمة سلام، ",
    mobily: "عند التحقق من هوم فايبر، ",
  };
  const districts = city.districts.map(([name, text], index) => ({ name, text: `${districtLeads[operator.slug]}${text} ${angle.endings[index % 2]}` }));
  const faqLeads = {
    stc: ["في باقات STC، ", "قبل طلب STC، "],
    salam: ["عند تقييم سلام، ", "قبل الاشتراك مع سلام، "],
    mobily: ["ضمن خيارات موبايلي، ", "قبل اختيار موبايلي، "],
  };
  const faqs = city.faqs.map((faq, index) => ({
    q: index === 0 ? `${faq.q.replace("؟", "")} عند اختيار ${operator.name}؟` : `${faq.q.replace("؟", "")} مع ${operator.name}؟`,
    a: `${faqLeads[operator.slug][index % 2]}${faq.a}${index === 2 ? " وتكتمل المراجعة بعد إرسال الموقع." : ""}`,
  }));
  return { ...city, intro, districts, faqs };
}
