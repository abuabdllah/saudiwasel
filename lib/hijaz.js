export function getHijazContent(city, operator) {
  const base = hijazCities[city];
  const copy = operatorCopy[city][operator.slug];
  const faqs = base.faqs.map((faq, index) => ({
    q: index === 0 ? `${faq.q.replace("؟", "")} مع ${operator.name}؟` : faq.q,
    a: index === 1 ? `${faq.a} ويمكن مراجعة خيار ${operator.name} بعد إرسال العنوان.` : faq.a,
  }));
  return {
    ...base,
    intro: copy.intro,
    districts: districtProfiles[city].map(([name, text], index) => ({ name, text: `${text} ${index % 2 ? copy.districtEnd : copy.districtEnd.replace("؛", "، ثم")} ` })),
    faqs,
  };
}

